import { test, expect } from '@playwright/test';
import fs from 'fs';
import path from 'path';

/**
 * GOOD STORAGE STATE TEST EXAMPLE
 * 
 * Why this is a GOOD test:
 * 1. Efficiency: Instead of logging in before every test (which is slow and adds load to the system), 
 *    this test reuses a pre-saved 'storageState' (cookies and localStorage).
 * 2. Playwright Best Practice: It demonstrates the recommended way to handle authentication globally 
 *    or per-project using the configuration, or manually as shown here for educational purposes.
 * 3. Atomic Tests: Since the user is already "logged in", the tests can focus immediately on verifying 
 *    protected features (like the Profile page) without boilerplate login steps.
 * 4. Separation of Concerns: One 'setup' task handles authentication, while multiple functional tests 
 *    consume the resulting state.
 * 5. Stable Locators: Uses 'data-test' attributes to ensure the test doesn't break when the UI's look changes.
 */

// In a real project, you would define this in playwright.config.ts as a 'setup' project.
// For this example, we show how to use it within a spec file.
const authFile = path.join(__dirname, '../../.auth/user.json');

test.describe('Account Profile - Good Storage State', () => {

  // We use the storage state saved during setup (or a manual login if needed)
  // In a real scenario, this 'authFile' would be generated by a 'setup' test.
  test.use({ storageState: fs.existsSync(authFile) ? authFile : undefined });

  test.beforeEach(async ({ page }) => {
    // If the auth file doesn't exist, we perform a manual login once for this example
    if (!fs.existsSync(authFile)) {
      console.log('Auth file not found, performing manual login...');
      await page.goto('/auth/login');
      await page.locator('[data-test="email"]').fill('customer@practicesoftwaretesting.com');
      await page.locator('[data-test="password"]').fill('welcome01');
      await page.locator('[data-test="login-submit"]').click();
      
      // Wait for login to complete and save state
      await expect(page).toHaveURL(/account/);
      
      // Ensure directory exists
      const authDir = path.dirname(authFile);
      if (!fs.existsSync(authDir)) {
        fs.mkdirSync(authDir, { recursive: true });
      }
      await page.context().storageState({ path: authFile });
    }
  });

  test('should display user profile information using saved state', async ({ page }) => {
    // Navigate directly to the profile page - no need to login again!
    await page.goto('/account/profile');

    // Verify profile fields are populated correctly
    // We use stable data-test locators identified in the website source
    await expect(page.locator('[data-test="first-name"]')).not.toBeEmpty();
    await expect(page.locator('[data-test="last-name"]')).not.toBeEmpty();
    await expect(page.locator('[data-test="email"]')).toHaveValue('customer@practicesoftwaretesting.com');
  });

  test('should allow navigating to other protected pages without re-login', async ({ page }) => {
    await page.goto('/account/messages');
    
    // Verify we are still logged in (e.g., page title or absence of login form)
    await expect(page).not.toHaveURL(/login/);
    const pageTitle = page.locator('h1');
    await expect(pageTitle).toBeVisible();
  });

});
